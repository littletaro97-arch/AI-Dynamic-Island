import assert from 'node:assert/strict';
import { foldSession } from '../harness-bridge/status.mjs';
const now=Date.now();
const header={type:'session',version:4,id:'test',createdAt:now};
const event=(type,data={},seq=1)=>({type,data,seq,time:now});
const start=event('turn/start',{turn:1});
assert.equal(foldSession([header,start]).state,'running');
assert.equal(foldSession([header,start,event('turn/end',{reason:{kind:'completed'}},2)]).state,'completed');
assert.equal(foldSession([header,start,event('turn/end',{reason:{kind:'error'}},2)]).state,'error');
assert.equal(foldSession([header,start,event('approval/asked',{id:'a'})]).state,'decision');
assert.equal(foldSession([header,start,event('approval/asked',{id:'a'}),event('approval/decided',{id:'a'})]).state,'running');
const ask=event('tool/call',{name:'ask_user_question',callId:'q'});
const pending=event('tool/result',{message:{toolCallId:'q',content:[{type:'text',text:'{"pending":true}'}]}});
assert.equal(foldSession([header,start,ask,pending,event('turn/end',{reason:{kind:'completed'}},5)]).state,'decision');
assert.equal(foldSession([header,start,ask,event('tool/result',{message:{toolCallId:'q'}})]).state,'running');
assert.equal(foldSession([header,start,event('turn/end',{reason:{kind:'aborted'}},2)]).completions.length,0);
assert.throws(()=>foldSession([{...header,version:5}]));
assert.equal(foldSession([header,{...start,time:now-3*60*60*1000}]).state,'unknown');
console.log('PASS Harness running/completed/error/decision, answered approval, timed questions, cancelled turn, unsupported version and stale open turn');
